"""Generate simulator tables and encoding docs from cpu/isa.yaml.

Outputs:
  sim/src/gen/isa_gen.h   enums, struct definitions
  sim/src/gen/isa_gen.c   op info and per-variant encoding tables
  sim/src/gen/exec_gen.c  instruction semantics (switch on op)
  cpu/gen/encoding_<V>.md encoding tables and opcode-space usage
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from isa import ROOT, Isa  # noqa: E402

OPNDS = ["rd", "rs", "rt", "rx", "pd", "ps", "pt", "pn", "cc", "sr", "scale", "ext",
         "imm", "disp", "target", "abs"]
ROLES = ["rd", "rs", "rt", "rx", "pd", "ps", "pt", "pn", "lr"]
MODES = [None, "d", "x", "pi", "pd", "a"]
SIGN = {"u": 0, "s": 1, "w": 2}


def opnd_enum(o):
    return "O_" + o.upper()


def mode_enum(m):
    return "M_" + (m.upper() if m else "NONE")


def flags_for(cls, ext=False):
    f = ["F_EXT"] if ext else []
    if cls in ("ld", "ldp"):
        f.append("F_LOAD")
    if cls in ("st", "stp"):
        f.append("F_STORE")
    if cls in ("ld", "st", "ldp", "stp", "lea"):
        f.append("F_MEM")
    if cls == "br":
        f.append("F_BRANCH")
    if cls in ("jal", "jr", "jalr"):
        f.append("F_JUMP")
    return "|".join(f) or "0"


def gen_header(isa):
    L = ["/* Generated by sim/tools/gen.py from cpu/isa.yaml. Do not edit. */",
         "#ifndef ISA_GEN_H", "#define ISA_GEN_H", "#include <stdint.h>", ""]
    L.append("enum {")
    L += [f"    OP_{op}," for op in isa.op_list]
    L += ["    OP__COUNT", "};", ""]
    L.append("enum {")
    L += [f"    CLS_{c.upper()}," for c in isa.classes]
    L += ["    CLS__COUNT", "};", ""]
    L.append("enum { " + ", ".join(opnd_enum(o) for o in OPNDS) + ", O__COUNT };")
    L.append("enum { " + ", ".join(mode_enum(m) for m in MODES) + " };")
    L.append("enum { " + ", ".join(f"ROLE_{r.upper()} = 1 << {i}" for i, r in enumerate(ROLES)) + " };")
    L.append("enum { F_LOAD = 1, F_STORE = 2, F_MEM = 4, F_BRANCH = 8, F_JUMP = 16, F_EXT = 32 };")
    L.append(f"#define NUM_CONDITIONS {len(isa.conditions)}")
    L += ["",
          "typedef struct {",
          "    const char *name;",
          "    uint8_t cls, size, flags;",
          "    uint16_t reads, writes;  /* ROLE_* masks */",
          "} opinfo_t;",
          "",
          "typedef struct {",
          "    uint8_t opnd, opnd2, sign, width, nruns, scale, div, pcrel;",
          "    uint8_t sh[4], wd[4];",
          "} fld_t;",
          "",
          "typedef struct {",
          "    uint32_t mask, value;",
          "    uint16_t op;",
          "    uint8_t len, mode, nf, nfix;",
          "    fld_t f[5];",
          "    uint8_t fixo[4];",
          "    int32_t fixv[4];",
          "    const char *name;",
          "} form_t;",
          "",
          "typedef struct {",
          "    const char *name, *doc;",
          "    int nlong;",
          "    uint16_t lmask[4], lval[4];",
          "    const form_t *forms;   /* 16-bit forms first, then 32-bit */",
          "    int n16, nforms;",
          "} variant_t;",
          "",
          "extern const opinfo_t op_info[OP__COUNT];",
          "extern const char *const cond_names[NUM_CONDITIONS];",
          "extern const char *const cls_names[CLS__COUNT];",
          "extern const variant_t *const variants[];",
          f"#define NUM_VARIANTS {len(isa.variants)}",
          "",
          "#endif"]
    return "\n".join(L) + "\n"


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_tables(isa):
    L = ["/* Generated by sim/tools/gen.py from cpu/isa.yaml. Do not edit. */",
         '#include "isa_gen.h"', ""]
    L.append("const opinfo_t op_info[OP__COUNT] = {")
    for op in isa.op_list:
        o = isa.ops[op]
        c = isa.classes[o["cls"]]
        reads = "|".join(f"ROLE_{r.upper()}" for r in c["reads"]) or "0"
        writes = "|".join(f"ROLE_{r.upper()}" for r in c["writes"]) or "0"
        L.append(f'    [OP_{op}] = {{ "{op}", CLS_{o["cls"].upper()}, {o.get("size", 0)}, '
                 f'{flags_for(o["cls"], o.get("ext"))}, {reads}, {writes} }},')
    L += ["};", ""]
    L.append("const char *const cond_names[NUM_CONDITIONS] = { " +
             ", ".join(c_str(c) for c in isa.conditions) + " };")
    L.append("const char *const cls_names[CLS__COUNT] = { " +
             ", ".join(c_str(c) for c in isa.classes) + " };")
    L.append("")
    vnames = []
    for v in isa.variants.values():
        arr = f"forms_{v.name}"
        L.append(f"static const form_t {arr}[] = {{")
        for f in v.forms:
            flds = []
            for fl in f.fields:
                runs = fl.runs()
                sh = ", ".join(str(s) for s, _ in runs)
                wd = ", ".join(str(w) for _, w in runs)
                o2 = opnd_enum(fl.spec.opnds[1]) if len(fl.spec.opnds) > 1 else "0xFF"
                flds.append(f"{{ {opnd_enum(fl.opnd)}, {o2}, {SIGN[fl.spec.sign]}, {fl.width}, {len(runs)}, "
                            f"{fl.spec.scale}, {fl.spec.div}, {int(fl.spec.pcrel)}, {{ {sh} }}, {{ {wd} }} }}")
            fixo = ", ".join(opnd_enum(k) for k in f.fixed) or "0"
            fixv = ", ".join(str(x) for x in f.fixed.values()) or "0"
            L.append(f"    {{ 0x{f.mask:08x}u, 0x{f.value:08x}u, OP_{f.op}, {f.len}, {mode_enum(f.mode)}, "
                     f"{len(f.fields)}, {len(f.fixed)}, {{ {', '.join(flds) or '{0}'} }}, "
                     f"{{ {fixo} }}, {{ {fixv} }}, {c_str(f.name())} }},")
        L += ["};", ""]
        n16 = sum(1 for f in v.forms if f.len == 16)
        lm = ", ".join(f"0x{m:04x}" for m, _ in v.long_rules)
        lv = ", ".join(f"0x{x:04x}" for _, x in v.long_rules)
        L.append(f"static const variant_t variant_{v.name} = {{ {c_str(v.name)}, {c_str(v.doc)}, "
                 f"{len(v.long_rules)}, {{ {lm} }}, {{ {lv} }}, {arr}, {n16}, {len(v.forms)} }};")
        vnames.append(f"&variant_{v.name}")
    L.append("")
    L.append("const variant_t *const variants[] = { " + ", ".join(vnames) + " };")
    return "\n".join(L) + "\n"


def gen_exec(isa):
    L = ["/* Generated by sim/tools/gen.py from cpu/isa.yaml. Do not edit. */",
         '#include "../cpu.h"', "",
         "#define rd (d->rd)", "#define rs (d->rs)", "#define rt (d->rt)", "#define rx (d->rx)",
         "#define pd (d->pd)", "#define ps (d->ps)", "#define pt (d->pt)", "#define pn (d->pn)",
         "#define cc (d->cc)", "#define sr (d->sr)", "#define imm (d->imm)", "",
         "void exec_inst(cpu_t *c, const dinst_t *d)", "{", "    switch (d->op) {"]
    for op in isa.op_list:
        L.append(f"    case OP_{op}: {{ {isa.ops[op]['sem']} }} break;")
    L += ["    default: TRAP(-2); break;", "    }", "}"]
    return "\n".join(L) + "\n"


def syntax(isa, op):
    o = isa.ops[op]
    opnds = isa.classes[o["cls"]]["opnds"]
    name = op + "cc" if op == "B" else op
    return (name + " " + ", ".join(opnds)).strip()


def pattern_str(f):
    """Pattern with fixed bits filled in, letters for fields."""
    letters = ["?"] * f.len
    for i in range(f.len):
        b = f.len - 1 - i
        if (f.mask >> b) & 1:
            letters[i] = str((f.value >> b) & 1)
    for fl in f.fields:
        ch = fl.spec.letter
        for p in fl.positions:
            letters[f.len - 1 - p] = ch
    s = "".join(letters)
    return " ".join(s[i:i + 4] for i in range(0, len(s), 4))


def opcode_space(v):
    short = [f for f in v.forms if f.len == 16]
    long_ = [f for f in v.forms if f.len == 32]
    n_long = n_short_used = n_long_used = 0
    for p in range(65536):
        if v.is_long(p):
            n_long += 1
            if any((p & (f.mask >> 16)) == (f.value >> 16) for f in long_):
                n_long_used += 1
        elif any((p & f.mask) == f.value for f in short):
            n_short_used += 1
    return n_long, n_long_used, 65536 - n_long, n_short_used


def gen_doc(isa, v):
    n_long, n_long_used, n_short, n_short_used = opcode_space(v)
    L = [f"# Encoding variant {v.name}", "",
         "Generated by `sim/tools/gen.py` from `cpu/isa.yaml`. Do not edit.", "",
         f"{v.doc}.", "",
         "## Opcode space (first 16-bit parcel)", "",
         "| | parcels | share | used |",
         "|---|---|---|---|",
         f"| 16-bit | {n_short} | {n_short / 655.36:.1f}% | {n_short_used} ({n_short_used / max(n_short, 1) * 100:.1f}%) |",
         f"| 32-bit prefix | {n_long} | {n_long / 655.36:.1f}% | {n_long_used} ({n_long_used / max(n_long, 1) * 100:.1f}%) |",
         "",
         f"{len(v.forms)} encodings: {sum(1 for f in v.forms if f.len == 16)} 16-bit, "
         f"{sum(1 for f in v.forms if f.len == 32)} 32-bit.", ""]
    groups = {}
    for f in v.forms:
        groups.setdefault(f.group, []).append(f)
    for g, fs in groups.items():
        L += [f"## {g}", "", "| encoding | bits | pattern | syntax |", "|---|---|---|---|"]
        for f in sorted(fs, key=lambda f: f.value):
            L.append(f"| `{f.name()}` | {f.len} | `{pattern_str(f)}` | `{syntax(isa, f.op)}` |")
        L.append("")
    return "\n".join(L)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as fh:
            fh.write(text)


def main():
    isa = Isa()
    gdir = os.path.join(ROOT, "sim", "src", "gen")
    write(os.path.join(gdir, "isa_gen.h"), gen_header(isa))
    write(os.path.join(gdir, "isa_gen.c"), gen_tables(isa))
    write(os.path.join(gdir, "exec_gen.c"), gen_exec(isa))
    for v in isa.variants.values():
        write(os.path.join(ROOT, "cpu", "gen", f"encoding_{v.name}.md"), gen_doc(isa, v))
    print("gen: ok")


if __name__ == "__main__":
    main()
