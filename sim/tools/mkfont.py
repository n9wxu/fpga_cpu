"""Build the 8x14 character ROM from a BDF font, in CP437 order.

  mkfont.py sim/assets/ter-u14n.bdf

Writes sim/assets/font8x14.mem (one byte per line, 14 rows per character,
for $readmemh in the FPGA) and sim/src/font8x14.c (the simulator's copy).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.dirname(HERE)

# CP437 glyphs for the control-code positions, then the rest from the codec.
LOW = (" ☺☻♥♦♣♠•◘○◙♂♀♪♫☼"
       "►◄↕‼¶§▬↨↑↓→←∟↔▲▼")


def cp437():
    m = [ord(ch) for ch in LOW]
    m += [ord(bytes([i]).decode("cp437")) for i in range(32, 256)]
    m[0x7F] = 0x2302
    return m


def load_bdf(path):
    glyphs, cur, rows, bbx = {}, None, None, None
    asc = 12
    for line in open(path, encoding="latin-1"):
        w = line.split()
        if not w:
            continue
        if w[0] == "FONT_ASCENT":
            asc = int(w[1])
        elif w[0] == "ENCODING":
            cur = int(w[1])
        elif w[0] == "BBX":
            bbx = [int(x) for x in w[1:5]]
        elif w[0] == "BITMAP":
            rows = []
        elif w[0] == "ENDCHAR":
            g = [0] * 14
            bw, bh, bx, by = bbx
            top = asc - (by + bh)  # first row of the glyph in the 14-row cell
            for i, r in enumerate(rows):
                y = top + i
                if 0 <= y < 14:
                    bits, nb = int(r, 16), len(r) * 4  # rows are left-aligned hex
                    g[y] = ((bits >> (nb - 8)) >> bx) & 0xFF
            glyphs[cur] = g
            rows = None
        elif rows is not None:
            rows.append(w[0])
    return glyphs


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(SIM, "assets", "ter-u14n.bdf")
    glyphs = load_bdf(src)
    rom, missing = [], []
    for code, u in enumerate(cp437()):
        g = glyphs.get(u)
        if g is None:
            missing.append(f"{code:02x}:U+{u:04X}")
            g = glyphs.get(0xFFFD, [0] * 14)
        rom.append(g)
    with open(os.path.join(SIM, "assets", "font8x14.mem"), "w") as f:
        f.write("// 8x14 character ROM, CP437 order, derived from Terminus (SIL OFL 1.1)\n")
        for g in rom:
            f.write("".join(f"{b:02x}\n" for b in g))
    with open(os.path.join(SIM, "src", "font8x14.c"), "w") as f:
        f.write("/* 8x14 character ROM, CP437 order. Generated by sim/tools/mkfont.py from\n"
                " * sim/assets/ter-u14n.bdf (Terminus, SIL Open Font License 1.1). */\n")
        f.write("#include <stdint.h>\n\nconst uint8_t font8x14[256][14] = {\n")
        for code, g in enumerate(rom):
            f.write("    {" + ", ".join(f"0x{b:02x}" for b in g) + f"}}, /* {code:02x} */\n")
        f.write("};\n")
    if missing:
        print("no glyph for", " ".join(missing))


if __name__ == "__main__":
    main()
