//===-- FCPUInstPrinter.h - print fpga_cpu instructions ---------*- C++ -*-===//

#ifndef LLVM_LIB_TARGET_FCPU_MCTARGETDESC_FCPUINSTPRINTER_H
#define LLVM_LIB_TARGET_FCPU_MCTARGETDESC_FCPUINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"
#include "llvm/MC/MCRegister.h"

namespace llvm {
class FCPUInstPrinter : public MCInstPrinter {
public:
  FCPUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &O, MCRegister Reg) const override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Generated by TableGen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst *MI) override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCC(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemD(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemX(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemA(const MCInst *MI, unsigned OpNo, raw_ostream &O);
};
} // namespace llvm

#endif
