#!/usr/bin/env python3
"""The Future: generated assets -> src/assets.h

  samples   drums (8-bit signed): kick, snare/clap, closed and open hat, crash; single-cycle waveforms
            (256 frames each, so a chip voice's step plays them at pitch): bass, lead, pluck, string
  planets   128 x 64 textures of tones 0-15 and a 16-colour ramp each: Mars, Jupiter, Saturn, Neptune
  sphere    the planet renderer's table for a sphere of radius 72 (half-resolution pixels): per row the
            half width and texture row, per pixel the longitude (0-63) and the light level
  font35    a 3 x 5 pixel font (the low-resolution eras' captions)
Everything is computed here, so the demo is original down to the drum hits."""
import math
import random
import sys

random.seed(1969)
out = []


def arr(ctype, name, data, per=24):
    out.append("static const %s %s[%d] = {" % (ctype, name, len(data)))
    for i in range(0, len(data), per):
        out.append("    " + ", ".join(str(v) for v in data[i:i + per]) + ",")
    out.append("};")


def s8(x):
    return max(-127, min(127, int(round(x * 127))))


# ------------------------------------------------------------------ samples
def noise():
    return random.uniform(-1, 1)


def kick(rate=16000, dur=0.30):
    n = int(rate * dur)
    ph = 0.0
    o = []
    for i in range(n):
        t = i / rate
        f = 46 + 120 * math.exp(-t / 0.028)
        ph += 2 * math.pi * f / rate
        a = math.exp(-t / 0.13)
        x = math.sin(ph) * a + (noise() * 0.5 * math.exp(-t / 0.003))
        o.append(math.tanh(1.8 * x) / math.tanh(1.8))
    return o


def hp(sig, k=0.6):  # one-pole high-pass
    o, prev, y = [], 0.0, 0.0
    for x in sig:
        y = k * (y + x - prev)
        prev = x
        o.append(y)
    return o


def snare(rate=16000, dur=0.24):
    n = int(rate * dur)
    nz = hp([noise() for _ in range(n)], 0.7)
    o = []
    for i in range(n):
        t = i / rate
        # a clap: three quick bursts, then the tail; a little body at 190 Hz
        env = math.exp(-t / 0.075)
        for b in (0.0, 0.011, 0.022):
            if b <= t < b + 0.008:
                env = max(env, 1.0 - (t - b) / 0.008 * 0.4)
        tone = math.sin(2 * math.pi * 190 * t) * math.exp(-t / 0.035) * 0.45
        o.append(max(-1, min(1, nz[i] * 1.3 * env + tone)))
    return o


def hat(rate=24000, dur=0.05, decay=0.012):
    n = int(rate * dur)
    # metallic: six square waves at inharmonic ratios, plus noise, high-passed
    fr = [3150, 4230, 5410, 6670, 7310, 8890]
    sig = []
    for i in range(n):
        t = i / rate
        m = sum(1 if math.sin(2 * math.pi * f * t) > 0 else -1 for f in fr) / 6
        sig.append(m * 0.6 + noise() * 0.6)
    sig = hp(hp(sig, 0.5), 0.5)
    return [max(-1, min(1, x * 1.8 * math.exp(-(i / rate) / decay))) for i, x in enumerate(sig)]


def crash(rate=16000, dur=0.85):
    n = int(rate * dur)
    fr = [2310, 3170, 4430, 5020, 6110]
    sig = []
    for i in range(n):
        t = i / rate
        m = sum(1 if math.sin(2 * math.pi * f * t + f) > 0 else -1 for f in fr) / 5
        sig.append(m * 0.4 + noise() * 0.8)
    sig = hp(sig, 0.6)
    return [max(-1, min(1, x * 1.2 * math.exp(-(i / rate) / 0.3) * (min(1, i / 40)))) for i, x in enumerate(sig)]


def cycle(harm):
    """a 256-frame single cycle from (harmonic, amplitude, phase) triples, normalised"""
    o = []
    for i in range(256):
        p = 2 * math.pi * i / 256
        o.append(sum(a * math.sin(h * p + ph) for h, a, ph in harm))
    m = max(abs(x) for x in o)
    return [x / m * 0.95 for x in o]


bass = cycle([(1, 1.0, 0), (2, 0.55, 0), (3, 0.30, 0), (4, 0.18, 0), (5, 0.10, 0), (6, 0.06, 0)])
lead = cycle([(h, 1.0 / h, 0) for h in range(1, 18)] + [(h, 0.35 / h, math.pi / 2) for h in range(1, 9, 2)])
pluck = cycle([(h, (1.0 / h) * (1 if h % 4 else 0.2), 0) for h in range(1, 14)])
string = cycle([(1, 1.0, 0), (2, 0.42, 0.7), (3, 0.30, 1.3), (4, 0.16, 0.2), (5, 0.12, 2.0), (6, 0.07, 0.4),
                (7, 0.05, 1.1)])

smp = {}
smp_list = [("kick", kick(), 16000), ("snare", snare(), 16000), ("chat", hat(), 24000),
            ("ohat", hat(24000, 0.24, 0.075), 24000), ("crash", crash(), 16000),
            ("bass", bass, 0), ("lead", lead, 0), ("pluck", pluck, 0), ("string", string, 0)]
blob = []
out.append("/* generated by tools/mkassets.py: do not edit */")
out.append("#include <stdint.h>")
for name, data, rate in smp_list:
    while len(blob) % 4:
        blob.append(0)
    off = len(blob)
    blob += [s8(x) & 0xFF for x in data]
    step = round(rate / 48000 * 65536) if rate else 0
    out.append("#define S_%s_OFF %d" % (name.upper(), off))
    out.append("#define S_%s_LEN %d" % (name.upper(), len(data)))
    if step:
        out.append("#define S_%s_STEP %d" % (name.upper(), step))
while len(blob) % 4:
    blob.append(0)
out.append("#define SAMPLES_LEN %d" % len(blob))
arr("uint8_t", "samples", blob, 32)


# ------------------------------------------------------------------ planet textures
def vnoise(seed, gw, gh):
    rnd = random.Random(seed)
    g = [[rnd.random() for _ in range(gw)] for _ in range(gh + 1)]

    def f(x, y):  # x wraps (gw), y clamps
        x0 = int(math.floor(x)) % gw
        y0 = max(0, min(gh - 1, int(math.floor(y))))
        fx, fy = x - math.floor(x), y - math.floor(y)
        fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
        a = g[y0][x0] * (1 - fx) + g[y0][(x0 + 1) % gw] * fx
        b = g[y0 + 1][x0] * (1 - fx) + g[y0 + 1][(x0 + 1) % gw] * fx
        return a * (1 - fy) + b * fy
    return f


def fbm(seed, x, y, oct=4):
    s, a, tot = 0.0, 1.0, 0.0
    for o in range(oct):
        f = NOISES[(seed, o)]
        sc = 2 ** o
        s += a * f(x * sc, y * sc)
        tot += a
        a *= 0.5
    return s / tot


NOISES = {}
for seed in range(1, 6):
    for o in range(5):
        NOISES[(seed, o)] = vnoise(seed * 100 + o, 8 * 2 ** o, 4 * 2 ** o)

TW, TH = 128, 64


def texture(fn):
    t = []
    for y in range(TH):
        for x in range(TW):
            v = fn(x / TW * 8, y / TH * 4, x, y)
            t.append(max(0, min(15, int(v))))
    return t


def mars(u, v, x, y):
    n = fbm(1, u, v, 5)
    lat = abs(y - 31.5) / 32
    if lat > 0.86 - 0.08 * fbm(2, u, v, 3):
        return 15                                              # polar cap
    c = 2 + n * 12
    # craters: dark rings at a few spots
    for cx, cy, r in ((20, 30, 4), (70, 22, 6), (100, 40, 3), (45, 45, 5)):
        d = math.hypot((x - cx), (y - cy))
        if d < r:
            c -= 3 * (1 - d / r)
    return min(14, c)


def jupiter(u, v, x, y):
    warp = fbm(3, u, v, 4) * 2.2
    band = math.sin((y / TH) * math.pi * 11 + warp) * 0.5 + 0.5
    c = 3 + band * 9 + (fbm(4, u * 2, v * 2, 3) - 0.5) * 4
    # the great spot
    dx, dy = (x - 80) / 9.0, (y - 40) / 4.5
    d = dx * dx + dy * dy
    if d < 1:
        return 14 if d < 0.6 else 13
    return min(11, c)


def saturn(u, v, x, y):
    band = math.sin((y / TH) * math.pi * 9 + fbm(5, u, v, 2) * 0.8) * 0.5 + 0.5
    return 4 + band * 8 + (fbm(1, u * 3, v * 3, 2) - 0.5) * 2


def neptune(u, v, x, y):
    band = math.sin((y / TH) * math.pi * 6 + fbm(2, u, v, 3) * 1.5) * 0.5 + 0.5
    c = 4 + band * 6
    dx, dy = (x - 40) / 7.0, (y - 38) / 3.5
    if dx * dx + dy * dy < 1:
        return 1
    if abs(y - 30 - 3 * math.sin(x / 9)) < 1.2 and fbm(3, u * 2, v, 2) > 0.62:
        return 15                                              # bright streak clouds
    return min(13, c)


def ramp(stops):
    """16 RGB565 colours through stops (index, r, g, b)"""
    o = []
    for i in range(16):
        for (i0, *c0), (i1, *c1) in zip(stops, stops[1:]):
            if i0 <= i <= i1:
                k = (i - i0) / max(1, i1 - i0)
                r, g, b = (int(c0[j] + (c1[j] - c0[j]) * k) for j in range(3))
                break
        o.append((r >> 3) << 11 | (g >> 2) << 5 | (b >> 3))
    return o


def terra(u, v, x, y):
    lat = abs(y - 31.5) / 32
    h = fbm(4, u * 1.3, v * 1.3, 5)
    cl = fbm(5, u * 2.5 + 3, v * 2.5, 4)
    if cl > 0.62:
        return 15                                              # clouds
    if lat > 0.88:
        return 14                                              # ice
    if h < 0.47:
        return 1 + int(h / 0.47 * 4)                           # ocean, deep to shallow
    if h < 0.5:
        return 7                                               # coast
    return 9 + int((h - 0.5) * 18)                             # land: green to brown


planets = [
    ("mars", mars, ramp([(0, 60, 20, 10), (6, 150, 60, 30), (12, 220, 130, 80), (14, 235, 170, 120),
                          (15, 250, 245, 240)])),
    ("jupiter", jupiter, ramp([(0, 90, 60, 40), (4, 160, 110, 70), (8, 220, 190, 150), (12, 250, 240, 220),
                               (13, 200, 90, 60), (15, 230, 120, 80)])),
    ("saturn", saturn, ramp([(0, 120, 100, 60), (6, 200, 170, 110), (12, 245, 225, 170), (15, 255, 245, 210)])),
    ("terra", terra, ramp([(0, 5, 15, 50), (2, 10, 40, 110), (4, 30, 90, 160), (6, 60, 140, 170), (7, 200, 190, 140),
                           (9, 50, 120, 50), (11, 70, 110, 40), (13, 140, 120, 80), (14, 235, 240, 250), (15, 255, 255, 255)])),
    ("neptune", neptune, ramp([(0, 10, 20, 70), (3, 30, 60, 160), (9, 70, 120, 230), (13, 120, 170, 250),
                               (15, 235, 245, 255)])),
]
for name, fn, pal in planets:
    t = [v >> 1 for v in texture(fn)]                          # 8 tones: the light gets 16 levels
    arr("uint8_t", "tex_" + name, t, 64)
    arr("uint16_t", "pal_" + name, pal[1::2], 8)

# ------------------------------------------------------------------ the sphere table
R = 72
L = (-0.80, -0.25, 0.55)
ll = math.sqrt(sum(c * c for c in L))
L = tuple(c / ll for c in L)
rows, ents = [], []
for j in range(-R, R):
    y = (j + 0.5) / R
    w = int(math.sqrt(max(0.0, 1 - y * y)) * R)
    v = int((math.asin(max(-1, min(1, y))) / math.pi + 0.5) * TH)
    v = max(0, min(TH - 1, v))
    rows.append((w, v))
    for i in range(-w, w):
        x = (i + 0.5) / R
        z = math.sqrt(max(0.0, 1 - x * x - y * y))
        wy = math.sqrt(max(1e-9, 1 - y * y))
        lon = math.asin(max(-1, min(1, x / wy)))
        u = int((lon / math.pi + 0.5) * 64)
        u = max(0, min(63, u))
        d = x * L[0] + y * L[1] + z * L[2]
        lit = max(0.0, d) ** 0.8 * (0.75 + 0.25 * z)            # a little limb darkening
        bay = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))[j & 3][i & 3] / 16.0
        sh = 1 + int(lit * 14.0 + bay)
        sh = max(1, min(15, sh))
        ents.append(u | (0x80 | sh << 3) << 8)
out.append("#define SPH_R %d" % R)
arr("uint8_t", "sph_w", [w for w, v in rows], 48)
arr("uint8_t", "sph_v", [v for w, v in rows], 48)
arr("uint16_t", "sph_e", ents, 24)

