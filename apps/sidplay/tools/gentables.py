#!/usr/bin/env python3
"""Writes src/tables.h: note frequency tables (PAL and NTSC SID frequency registers), the filter
cutoff curve (SID FC -> engine FCUT) and the resonance (SID res -> engine FRES damping)."""
import math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(HERE, "..", "src", "tables.h")

def nf(clock):
    return [min(65535, round(440.0 * 2 ** ((n - 57) / 12.0) * 16777216 / clock)) for n in range(96)]

def fcut(fc):
    """SID cutoff register (0..2047) -> engine FCUT = 2 sin(pi f/48000) x 32768, clamped to 0x7000.
    The curve is a 6581-ish compromise: f = 30 + 12000 (FC/2047)^1.25 Hz (the 6581 varies with the chip)."""
    f = 30 + 12000.0 * (min(fc, 2047) / 2047.0) ** 1.25
    return min(0x7000, round(2 * math.sin(math.pi * f / 48000.0) * 32768))

def damp(res):
    """SID resonance 0..15 -> engine FRES = 32768 / Q; Q = 0.707 + 0.25 res (res 15: Q about 4.5)."""
    q = 0.707 + 0.25 * res
    return min(0xFFFF, round(32768 / q))

with open(out, "w") as f:
    f.write("/* generated by tools/gentables.py */\n#include <stdint.h>\n")
    for name, clk in (("note_pal", 985248), ("note_ntsc", 1022727)):
        f.write("static const uint16_t %s[96] = {" % name)
        f.write(",".join(str(v) for v in nf(clk)) + "};\n")
    f.write("static const uint16_t fcut_tab[129] = {" + ",".join(str(fcut(min(i * 16, 2047))) for i in range(129)) + "};\n")
    f.write("static const uint16_t fres_tab[16] = {" + ",".join(str(damp(r)) for r in range(16)) + "};\n")
print("wrote", out)
