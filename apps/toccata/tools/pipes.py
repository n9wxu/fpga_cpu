#!/usr/bin/env python3
"""toccata's organ pipes, as 16-bit C arrays. A registration's flue ranks are drawn together into
one sample: an 8' rank's 4', 2 2/3' and 2' are its 2nd, 3rd and 4th harmonics, so a note sounds a
whole chorus from one engine node (the reeds stay a node of their own, beating against it). Each
in four ranges so no harmonic passes 20 kHz at the top of its range and the engine's step stays
under 1.4 (its 48-frame window); a rank's harmonics above the range's limit drop out, as a
mixture breaks back. A sample is a 1024-frame loop of whole cycles: a pipe is steady.
    range  period  cycles  base Hz  used for MIDI   harmonics
    0      128     8       375      <= 72 (C5)      to 20 kHz at 523 Hz: 38
    1      64      16      750      73-84 (C6)      19
    2      32      32      1500     85-96 (C7)      9
    3      16      64      3000     97-108 (C8)     4
usage: pipes.py OUT.h"""
import math
import random
import sys

N = 1024
RANGES = [(128, 72, 38), (64, 84, 19), (32, 96, 9), (16, 108, 4)]   # period, top MIDI, harmonics
random.seed(565)


def principal(h):    # a diapason: the fundamental strong, a steady fall, the octave a little up
    return h ** -1.4 * (1.25 if h == 2 else 1.0)


def stopped(h):      # a stopped flute (Subbass, Gedackt): odd harmonics, soft
    return (1.0, 0.0, 0.28, 0.0, 0.10, 0.0, 0.04, 0.0, 0.015)[h - 1] + 0.02 / h if h <= 9 else 0.0


def reed(h):         # a trumpet / trombone: rich, a broad peak, then falling
    return h ** -0.55 * (1.0 if h <= 10 else math.exp(-(h - 10) / 7))


# the timbres: (name, [(stop, rank's multiple of the fundamental, gain)])
TIMBRES = [
    ("man_soft", [(principal, 1, 1.0), (stopped, 2, 0.55)]),                              # 8', flute 4'
    ("man_mid", [(principal, 1, 1.0), (principal, 2, 0.7), (stopped, 1, 0.5)]),          # 8', 4', flute 8'
    ("man_full", [(principal, 1, 1.0), (principal, 2, 0.7), (principal, 3, 0.4), (principal, 4, 0.5)]),   # + 2 2/3', 2'
    ("ped", [(stopped, 1, 1.0), (principal, 2, 0.6)]),                                   # Subbass 16', 8'
    ("ped_full", [(stopped, 1, 1.0), (principal, 2, 0.65), (principal, 4, 0.4)]),         # + 4'
    ("reed", [(reed, 1, 1.0)]),                                                          # trumpet, trombone
]


def wave(ranks, period, nh):
    amp = {}
    for fn, mult, g in ranks:                  # the ranks' partials, as harmonics of the fundamental
        for h in range(1, nh + 1):
            k = h * mult
            if k > nh or 2 * k >= period:
                break
            amp[k] = amp.get(k, 0.0) + g * fn(h)
    x = [0.0] * N
    for k, a in sorted(amp.items()):
        if a == 0:
            continue
        ph = random.uniform(0, 2 * math.pi)
        w = 2 * math.pi * k / period
        for i in range(N):
            x[i] += a * math.sin(w * i + ph)
    pk = max(abs(v) for v in x)
    return [round(v / pk * 30000) for v in x]


def main():
    with open(sys.argv[1], "w") as f:
        f.write("/* generated by apps/toccata/tools/pipes.py: organ registrations, 4 ranges each, 1024-frame loops */\n")
        f.write("#define PIPE_LEN %d\n" % N)
        f.write("static const uint8_t pipe_top[4] = { %s };\n" % ", ".join(str(r[1]) for r in RANGES))
        f.write("static const uint8_t pipe_shift[4] = { 9, 10, 11, 12 };   /* step: the oscillator step >> this */\n")
        names = []
        for sn, ranks in TIMBRES:
            for k, (period, top, nh) in enumerate(RANGES):
                d = wave(ranks, period, nh)
                d = d + d[:104]                    # the engine's window reads on past the loop's end
                name = "pipe_%s%d" % (sn, k)
                names.append(name)
                f.write("static const int16_t %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(d)))
                for i in range(0, len(d), 16):
                    f.write("    " + ", ".join(str(v) for v in d[i:i + 16]) + ",\n")
                f.write("};\n")
        f.write("enum { %s };\n" % ", ".join("T_" + t[0].upper() for t in TIMBRES))
        f.write("static const int16_t *const pipe[%d][4] = {\n" % len(TIMBRES))
        for s in range(len(TIMBRES)):
            f.write("    { %s },\n" % ", ".join(names[4 * s:4 * s + 4]))
        f.write("};\n")


if __name__ == "__main__":
    main()
