#!/usr/bin/env python3
"""The demo's 8-bit samples, as C arrays: a kick, a snare, a hi-hat (one-shots) and a plucked string
(Karplus-Strong at 110.09 Hz: 436 frames a period, looped over its last 4 periods, so the loop's start
and length are multiples of 4 frames, as the engine's smp routine needs).
usage: samples.py OUT.h"""
import math
import random
import sys

random.seed(5)


def kick(n=5200):
    out, ph = [], 0.0
    for i in range(n):
        t = i / 48000
        f = 45 + 110 * math.exp(-t * 28)
        ph += 2 * math.pi * f / 48000
        a = math.exp(-t * 7.5) * (1.0 if i > 30 else i / 30)
        out.append(math.sin(ph) * a + (random.uniform(-1, 1) * 0.25 * math.exp(-t * 300)))
    return out


def snare(n=7200):
    out, ph, prev = [], 0.0, 0.0
    for i in range(n):
        t = i / 48000
        ph += 2 * math.pi * 185 / 48000
        nz = random.uniform(-1, 1)
        hp = nz - prev * 0.6
        prev = nz
        out.append(0.55 * hp * math.exp(-t * 16) + 0.55 * math.sin(ph) * math.exp(-t * 30))
    return out


def hat(n=2400):
    out, prev = [], 0.0
    for i in range(n):
        t = i / 48000
        nz = random.uniform(-1, 1)
        out.append((nz - prev) * 0.5 * math.exp(-t * 60))
        prev = nz
    return out


def pluck(period=436, periods=40):
    buf = [random.uniform(-1, 1) for _ in range(period)]
    # soften the burst a little: a brighter but not harsh attack
    buf = [(buf[i] + buf[i - 1]) / 2 for i in range(period)]
    out = []
    for i in range(period * periods):
        v = buf[i % period]
        out.append(v)
        buf[i % period] = 0.4985 * (v + buf[(i + 1) % period])
    # the loop: the last 4 periods (the string loses about 1% over them, so the join is small)
    return out, len(out) - 4 * period


def to8(x, gain=1.0):
    pk = max(abs(v) for v in x) or 1
    return [max(-127, min(127, int(round(v / pk * 120 * gain)))) for v in x]


def carray(f, name, data):
    n = (len(data) + 3) & ~3
    data = data + [0] * (n - len(data) + 132)      # (the engine's window reads up to 128 frames on)
    f.write("static const int8_t %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(data)))
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join(str(v) for v in data[i:i + 24]) + ",\n")
    f.write("};\n")
    return n


def main():
    with open(sys.argv[1], "w") as f:
        f.write("/* generated by apps/mcdemo/tools/samples.py: 8-bit signed, 48 kHz */\n")
        for name, x in (("kick", kick()), ("snare", snare()), ("hat", hat())):
            n = carray(f, "smp_" + name, to8(x))
            f.write("#define SMP_%s_LEN %d\n" % (name.upper(), n))
        p, ls = pluck()
        n = carray(f, "smp_pluck", to8(p))
        f.write("#define SMP_PLUCK_LEN %d\n#define SMP_PLUCK_LOOP %d\n#define SMP_PLUCK_MIDI 45\n" % (len(p), ls))


if __name__ == "__main__":
    main()
