#!/usr/bin/env python3
"""gentables.py: src/tables.h for modplay: the ProTracker period table (16 finetunes x 36 notes, C-1..B-3),
the vibrato/tremolo sine (32 entries, 0..255), and the note names."""
import math, os
# ProTracker's finetune-0 row, as it ships (the other finetunes from it by 2^(-ft/96), rounded)
ft0 = [856, 808, 762, 720, 678, 640, 604, 570, 538, 508, 480, 453,
       428, 404, 381, 360, 339, 320, 302, 285, 269, 254, 240, 226,
       214, 202, 190, 180, 170, 160, 151, 143, 135, 127, 120, 113]
rows = []
for ft in range(16):
    f = ft if ft < 8 else ft - 16           # 0..7, then -8..-1
    rows.append([ft0[n] if f == 0 else round(856 * 2 ** (-n / 12) * 2 ** (-f / 96)) for n in range(36)])
sine = [round(255 * math.sin(math.pi * i / 32)) for i in range(32)]
out = os.path.join(os.path.dirname(__file__), "..", "src", "tables.h")
with open(out, "w") as f:
    f.write("/* generated by tools/gentables.py */\n#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n")
    f.write("static const uint16_t periods[16][36] = {\n")
    for r in rows:
        f.write("    {" + ", ".join(str(p) for p in r) + "},\n")
    f.write("};\n")
    f.write("static const uint8_t vib_sine[32] = {" + ", ".join(str(s) for s in sine) + "};\n")
    f.write("#endif\n")
print("wrote", out)
