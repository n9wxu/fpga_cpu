#!/usr/bin/env python3
"""sym40's sampled instruments, as 16-bit C arrays: string sections and horns, each one loop of 8192
frames holding exactly 128 cycles of its base pitch (750 Hz at 48 kHz, so a note's step 16.16 is the
oscillator step >> 10). Band-limited (no harmonic above 20 kHz at the highest note used), built from
three detuned copies (127, 128 and 129 cycles in the loop) for an ensemble's chorus.
usage: instruments.py OUT.h"""
import math
import random
import sys

N, CYC = 8192, 128
random.seed(40)


def ensemble(amps, copies=((127, 0.8), (128, 1.0), (129, 0.8))):
    x = [0.0] * N
    for cyc, g in copies:
        ph = [random.uniform(0, 2 * math.pi) for _ in amps]
        for h, a in enumerate(amps, 1):
            if a == 0:
                continue
            w = 2 * math.pi * cyc * h / N
            for i in range(N):
                x[i] += g * a * math.sin(w * i + ph[h - 1])
    pk = max(abs(v) for v in x)
    return [max(-32767, min(32767, round(v / pk * 30000))) for v in x]


def violin():   # bright, a bowed string's falling harmonics with a body bump around the 4th-6th
    return [1 / h * math.exp(-h / 9) * (1.4 if 4 <= h <= 6 else 1.0) for h in range(1, 13)]


def low_strings():   # violas, cellos, basses: warmer
    return [1 / h * math.exp(-h / 5) for h in range(1, 13)]


def horn():   # round: strong low harmonics, little above the 6th
    return [1.0, 0.85, 0.55, 0.32, 0.18, 0.10, 0.05, 0.03]


def carray(f, name, data):
    data = data + data[:104]                   # (the engine's window reads up to 96 frames on: the loop again)
    f.write("static const int16_t %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(data)))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(str(v) for v in data[i:i + 16]) + ",\n")
    f.write("};\n")


def main():
    with open(sys.argv[1], "w") as f:
        f.write("/* generated by apps/sym40/tools/instruments.py: 16-bit, 8192-frame loops, 128 cycles of 750 Hz */\n")
        f.write("#define INS_LEN %d\n" % N)
        carray(f, "ins_violin", ensemble(violin()))
        carray(f, "ins_lowstr", ensemble(low_strings()))
        carray(f, "ins_horn", ensemble(horn(), ((128, 1.0), (129, 0.7))))


if __name__ == "__main__":
    main()
