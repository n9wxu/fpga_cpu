#!/usr/bin/env python3
"""Generate src/optable.h from tools/m6502.py (the one opcode table)."""
import os
import sys
sys.path.insert(0, os.path.dirname(__file__))
import m6502 as M

mn_ids = {m: i + 1 for i, m in enumerate(M.MNEMS)}
out = ["/* Generated by tools/gen_optable.py from m6502.py. Do not edit. */",
       "#ifndef OPTABLE_H", "#define OPTABLE_H", "#include <stdint.h>", ""]
out.append("enum {\n    N_ILL = 0,\n" + "".join(f"    N_{m} = {i},\n" for m, i in mn_ids.items()) + "};")
out.append("enum { AM_IMP, AM_ACC, AM_IMM, AM_ZP, AM_ZPX, AM_ZPY, AM_ABS, AM_ABX, AM_ABY, AM_IND, AM_IZX, AM_IZY, AM_REL };")


def arr(name, f, t="uint8_t"):
    vals = [f(o) if o else 0 for o in M.OPS]
    rows = [", ".join(f"{v:3d}" for v in vals[i:i + 16]) for i in range(0, 256, 16)]
    out.append(f"static const {t} {name}[256] = {{\n    " + ",\n    ".join(rows) + "\n};")


arr("op_mn", lambda o: mn_ids[o[0]])
arr("op_mode", lambda o: o[1])
arr("op_cyc", lambda o: o[2])
arr("op_pen", lambda o: int(o[3]))
arr("op_len", lambda o: M.MODE_LEN[o[1]])
arr("op_fr", lambda o: M.FLAGS.get(o[0], (0, 0))[0])
arr("op_fw", lambda o: M.FLAGS.get(o[0], (0, 0))[1])
out.append("#endif")
open(os.path.join(os.path.dirname(__file__), "..", "src", "optable.h"), "w").write("\n".join(out) + "\n")
